#!/usr/bin/env bash
# Make nginx forward CF-Connecting-IP ONLY when the request really came from Cloudflare.
# Direct hits on the origin get CF-Connecting-IP overwritten with their real address, so the app's
# rate limits / API IP allow-list can't be bypassed by faking the header.
# Affects only the cheapseller.store server block. Run:  sudo bash scripts/nginx-trust-cloudflare.sh
set -euo pipefail

SITE=/etc/nginx/sites-enabled/cheapseller.store
SNIP=/etc/nginx/conf.d/cheapseller-cf-trust.conf

grep -q "conf.d/\*.conf" /etc/nginx/nginx.conf || { echo "nginx.conf does not include conf.d/*.conf"; exit 1; }

V4=$(curl -fsS https://www.cloudflare.com/ips-v4)
V6=$(curl -fsS https://www.cloudflare.com/ips-v6)

{
  echo "# Generated by scripts/nginx-trust-cloudflare.sh"
  echo "geo \$cs_from_cf {"
  echo "    default 0;"
  for r in $V4 $V6; do echo "    $r 1;"; done
  echo "}"
  echo "map \$cs_from_cf \$cs_client_ip {"
  echo "    1 \$http_cf_connecting_ip;"
  echo "    default \$remote_addr;"
  echo "}"
} > "$SNIP"

cp "$SITE" "$SITE.bak-cf-trust"
if ! grep -q "cs_client_ip" "$SITE"; then
  sed -i '0,/proxy_set_header X-Real-IP \$remote_addr;/s//proxy_set_header X-Real-IP $remote_addr;\n        proxy_set_header CF-Connecting-IP $cs_client_ip;/' "$SITE"
fi

if nginx -t; then
  systemctl reload nginx
  echo "OK: cheapseller.store now trusts CF-Connecting-IP only from Cloudflare."
else
  echo "nginx -t failed, restoring"; cp "$SITE.bak-cf-trust" "$SITE"; rm -f "$SNIP"; exit 1
fi
